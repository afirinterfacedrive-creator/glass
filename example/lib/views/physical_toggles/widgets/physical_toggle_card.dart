
import 'package:flutter/material.dart';

import 'package:universal_glass/theme/glass_color_palette.dart';

import 'physical_toggle_header.dart';
import 'physical_toggle_shell.dart';
import 'physical_toggle_status.dart';

// ============================================================================
// PHYSICAL TOGGLE CARD
// ============================================================================
//
// Carte générique pour un contrôle physique.
//
// ARCHITECTURE
//
// PhysicalToggleCard
//      │
//      ├── PhysicalToggleHeader
//      │
//      ├── PhysicalToggleShell
//      │       │
//      │       ├── GlassColorPalette
//      │       └── child
//      │
//      └── PhysicalToggleStatus
//
// ============================================================================
//
// RESPONSABILITÉS
//
// - recevoir les données d'affichage
// - recevoir l'état du contrôle
// - recevoir la palette Glass
// - composer le Header
// - composer le Shell Glass
// - afficher le contrôle reçu via `child`
// - composer le Status
//
// ============================================================================
//
// NE GÈRE PAS
//
// - Riverpod
// - navigation
// - logique métier
// - état interne du toggle
// - callback du toggle
// - type du toggle
// - création de la palette
// - récupération de la palette
//
// La palette est injectée depuis le parent.
//
// Le contrôle réel est entièrement fourni via `child`.
//
// ============================================================================
//
// FLUX
//
// ControlPanelPage
//       │
//       ▼
// GlassColorPalette
//       │
//       ▼
// PhysicalTogglesSection
//       │
//       ▼
// PhysicalToggleCard
//       │
//       ├── palette
//       │
//       ▼
// PhysicalToggleShell
//
// ============================================================================

class PhysicalToggleCard extends StatelessWidget {
  // ==========================================================================
  // INFORMATIONS
  // ==========================================================================

  final String title;

  final String subtitle;

  final IconData icon;

  // ==========================================================================
  // ÉTAT D'AFFICHAGE
  // ==========================================================================

  final bool value;

  // ==========================================================================
  // COULEUR D'ACCENT
  // ==========================================================================

  final Color accent;

  // ==========================================================================
  // PALETTE GLASS
  // ==========================================================================
  //
  // Palette centrale injectée depuis l'extérieur.
  //
  // PhysicalToggleCard ne connaît pas Riverpod.
  //
  // ==========================================================================

  final GlassColorPalette palette;

  // ==========================================================================
  // TOGGLE
  // ==========================================================================

  final Widget child;

  // ==========================================================================
  // DIMENSIONS OPTIONNELLES
  // ==========================================================================

  final double? width;

  final double? height;

  // ==========================================================================
  // PADDING
  // ==========================================================================

  final EdgeInsetsGeometry padding;

  // ==========================================================================
  // CONSTRUCTEUR
  // ==========================================================================

  const PhysicalToggleCard({
    super.key,

    // ------------------------------------------------------------------------
    // INFORMATIONS
    // ------------------------------------------------------------------------

    required this.title,
    required this.subtitle,
    required this.icon,

    // ------------------------------------------------------------------------
    // ÉTAT
    // ------------------------------------------------------------------------

    required this.value,

    // ------------------------------------------------------------------------
    // ACCENT
    // ------------------------------------------------------------------------

    required this.accent,

    // ------------------------------------------------------------------------
    // PALETTE
    // ------------------------------------------------------------------------

    required this.palette,

    // ------------------------------------------------------------------------
    // TOGGLE
    // ------------------------------------------------------------------------

    required this.child,

    // ------------------------------------------------------------------------
    // DIMENSIONS
    // ------------------------------------------------------------------------

    this.width,
    this.height,

    // ------------------------------------------------------------------------
    // PADDING
    // ------------------------------------------------------------------------

    this.padding = const EdgeInsets.all(15),
  });

  // ==========================================================================
  // BUILD
  // ==========================================================================

  @override
  Widget build(BuildContext context) {
    return PhysicalToggleShell(
      // =======================================================================
      // ÉTAT
      // =======================================================================

      value: value,

      // =======================================================================
      // ACCENT
      // =======================================================================

      accent: accent,

      // =======================================================================
      // PALETTE
      // =======================================================================

      palette: palette,

      // =======================================================================
      // DIMENSIONS
      // =======================================================================

      width: width,

      height: height,

      // =======================================================================
      // PADDING
      // =======================================================================

      padding: padding,

      // =======================================================================
      // CONTENU
      // =======================================================================

      child: Column(
        mainAxisSize: MainAxisSize.min,

        crossAxisAlignment:
            CrossAxisAlignment.stretch,

        children: [
          // ===================================================================
          // HEADER
          // ===================================================================

          PhysicalToggleHeader(
            title: title,
            subtitle: subtitle,
            icon: icon,
            value: value,
            accent: accent,
          ),

          const SizedBox(
            height: 12,
          ),

          // ===================================================================
          // TOGGLE
          // ===================================================================
          //
          // Le contrôle conserve sa taille naturelle.
          //
          // Aucun Expanded.
          // Aucun height imposé.
          //
          // Cela évite les RenderFlex overflow sur mobile.
          //
          // ===================================================================

          Center(
            child: child,
          ),

          const SizedBox(
            height: 10,
          ),

          // ===================================================================
          // STATUS
          // ===================================================================

          PhysicalToggleStatus(
            value: value,
            accent: accent,
          ),
        ],
      ),
    );
  }
}

